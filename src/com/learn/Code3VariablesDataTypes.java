package com.learn;

public class Code2VariablesDataTypes
{
    public static void main(String[] args)
    {
        int age= 29;//define integer number or a numerical value;
        byte age1= 30;//define the byte value
        float age2= 29.6f;//define floating point number
        double age3= 29.6d;//define double number, we can write d at the last
        char c= '3';//define the character in single quote
        String str= "abhishek Sharma";//define the string in inverted commas
        System.out.println(age);
        System.out.println(age1);
        System.out.println(age2);
        System.out.println(age3);
        System.out.println(c);
        System.out.println(str);
    }
}
//literals are those whose value is constant and do not throughout the program
//how to define the variable with constant value for string, characters, long, short, byte and for float and double
